    // LOAD AKTIVITAS
    // =====================================

    private void loadAktivitas() {

        try {

            Connection c =
                    Koneksi.getConnection();

            String sql =
                    "SELECT u.nama_lengkap, "
                    + "b.judul, "
                    + "p.status "
                    + "FROM peminjaman p "
                    + "JOIN users u "
                    + "ON p.user_id=u.id "
                    + "JOIN detail_peminjaman d "
                    + "ON p.id=d.peminjaman_id "
                    + "JOIN buku b "
                    + "ON d.buku_id=b.id "
                    + "ORDER BY p.id DESC "
                    + "LIMIT 5";

            PreparedStatement p =
                    c.prepareStatement(sql);

            ResultSet r =
                    p.executeQuery();

            txtAktivitas.setText("");

            while(r.next()) {

                txtAktivitas.append(

                        r.getString("nama_lengkap")
                        + " - "

                        + r.getString("status")
                        + " buku "

                        + r.getString("judul")

                        + "\n"
                );
            }

        } catch(Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    e.getMessage()
            );
        }
    }

