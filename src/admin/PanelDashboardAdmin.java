    private void loadStatistik() {

        try {

            Connection c =
                    Koneksi.getConnection();

            // TOTAL BUKU

            String sqlBuku =
                    "SELECT COUNT(*) AS total "
                    + "FROM buku";

            PreparedStatement pBuku =
                    c.prepareStatement(sqlBuku);

            ResultSet rBuku =
                    pBuku.executeQuery();

            if(rBuku.next()) {

                lblTotalBuku.setText(
                        rBuku.getString("total")
                );
            }

            // TOTAL USER

            String sqlUser =
                    "SELECT COUNT(*) AS total "
                    + "FROM users";

            PreparedStatement pUser =
                    c.prepareStatement(sqlUser);

            ResultSet rUser =
                    pUser.executeQuery();

            if(rUser.next()) {

                lblTotalUser.setText(
                        rUser.getString("total")
                );
            }

            // TOTAL PEMINJAMAN

            String sqlPinjam =
                    "SELECT COUNT(*) AS total "
                    + "FROM peminjaman";

            PreparedStatement pPinjam =
                    c.prepareStatement(sqlPinjam);

            ResultSet rPinjam =
                    pPinjam.executeQuery();

            if(rPinjam.next()) {

                lblTotalPinjam.setText(
                        rPinjam.getString("total")
                );
            }

            // TOTAL PENGEMBALIAN

            String sqlKembali =
                    "SELECT COUNT(*) AS total "
                    + "FROM peminjaman "
                    + "WHERE status='dikembalikan'";

            PreparedStatement pKembali =
                    c.prepareStatement(sqlKembali);

            ResultSet rKembali =
                    pKembali.executeQuery();

            if(rKembali.next()) {

                lblTotalKembali.setText(
                        rKembali.getString("total")
                );
            }

        } catch(Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    e.getMessage()
            );
        }
    }

